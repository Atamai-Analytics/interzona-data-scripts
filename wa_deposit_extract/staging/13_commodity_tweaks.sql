-- WA deposit extract — Step 4c: commodity tweaks from spot-check review.
--   * drop source-flagged uncertain commodities ("Copper?", "cobalt?", "reportedly nickel")
--     — the definite primary_commodity still carries the real one (07_commodities.sql wa_tok)
--   * map "special clays - expanding clays and shales" -> Clay (was over the length cap)
-- Re-derives wa_canonical_commodity_tok (07) + the crosswalk (08), then re-syncs the
-- loaded deposit_commodities for this load. deposit.jsonl / deposit_endowment.jsonl
-- rebuilt afterwards. Run 07 + 08 (Python) before this file; it re-syncs the DB.

\set ON_ERROR_STOP on

-- (assumes 07_commodities.sql already re-run so wa_canonical_commodity_tok is current,
--  and crosswalk_commodity_wa.csv regenerated by 08_crosswalk.py)

BEGIN;

DROP TABLE IF EXISTS wa_commodity_xwalk_raw;
CREATE TABLE wa_commodity_xwalk_raw (
    token text, n_deposits int, n_primary int,
    commodity_id text, commodity_name text, method text);
\copy wa_commodity_xwalk_raw FROM 'C:/Users/dean/claude_lithosurfer/lithosurfer-work/wa_deposit_extract/staging/crosswalk_commodity_wa.csv' WITH (FORMAT csv, HEADER true)

DROP TABLE IF EXISTS wa_commodity_xwalk;
CREATE TABLE wa_commodity_xwalk AS
SELECT DISTINCT token, commodity_id::int AS commodity_id
FROM wa_commodity_xwalk_raw
WHERE method <> 'DROP' AND btrim(coalesce(commodity_id, '')) <> '';
ALTER TABLE wa_commodity_xwalk ADD PRIMARY KEY (token, commodity_id);

-- re-sync deposit_commodities for the WA load
DELETE FROM deposit_commodities WHERE createdby = 'claude_wa_20260910';

INSERT INTO deposit_commodities (depositid, commodity_id, commodity_role, createdby)
SELECT d.depositid, x.commodity_id,
       CASE WHEN bool_or(t.role = 'PRIMARY') THEN 'PRIMARY' ELSE 'SECONDARY' END,
       'claude_wa_20260910'
FROM wa_canonical_commodity_tok t
JOIN wa_commodity_xwalk x USING (token)
JOIN locations l ON l.external_id = 'WA:' || t.canonical_id AND l.createdby = 'claude_wa_20260910'
JOIN deposits  d ON d.locationid = l.locationid
GROUP BY d.depositid, x.commodity_id;

-- refresh deposits.comments (the "Ore minerals" line is unchanged, but keep in lockstep)
UPDATE deposits d
SET comments = regexp_replace(concat_ws(' | ',
        nullif(btrim(c.comments_all), ''),
        CASE WHEN nullif(btrim(c.value_all), '') IS NOT NULL
             THEN 'Value / significance: ' || c.value_all END,
        CASE WHEN array_length(c.ore_mineral_tokens, 1) IS NOT NULL
             THEN 'Ore minerals (DGER): ' || array_to_string(c.ore_mineral_tokens, ', ') END,
        CASE WHEN c.any_assay_flag THEN 'Assays recorded in DGER source.' END,
        'LithoSurfer sourceId: WA:' || c.canonical_id
     ), E'[ \t]*[\r\n\t·]+[ \t·]*', ' | ', 'g')
FROM wa_dedup_canonical c
JOIN locations l ON l.external_id = 'WA:' || c.canonical_id AND l.createdby = 'claude_wa_20260910'
WHERE d.locationid = l.locationid;

COMMIT;

\echo '--- deposit_commodities after re-sync ---'
SELECT commodity_role, count(*) FROM deposit_commodities WHERE createdby='claude_wa_20260910' GROUP BY 1;
\echo '--- deposits with zero commodity ---'
SELECT count(*) FROM locations l JOIN deposits d USING(locationid)
WHERE l.createdby='claude_wa_20260910'
  AND NOT EXISTS (SELECT 1 FROM deposit_commodities dc WHERE dc.depositid=d.depositid);
\echo '--- any "?" left in a mapped token ---'
SELECT count(*) FROM wa_canonical_commodity_tok t JOIN wa_commodity_xwalk x USING(token) WHERE t.token ~ '\?';
