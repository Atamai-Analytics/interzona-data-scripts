-- Phase 1, step 1: new child table + backups.  criticialmineralsexp, 2026-09-10.
-- Additive DDL; backups are full snapshots of the two tables Phase 1 modifies.

BEGIN;

-- 1. New child table: quantitative endowment (grade / tonnage / contained metal).
--    One row per SIGAM fact-sheet grade or amount value (faithful lift of sigam_ficha_grades
--    with commodity_id + depositid resolved). RESOURCE vs PRODUCTION kept; units NOT normalised.
CREATE TABLE IF NOT EXISTS deposit_endowment (
    deposit_endowment_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    depositid             integer NOT NULL REFERENCES deposits(depositid) ON DELETE CASCADE,
    commodity_id          integer REFERENCES commodities(commodity_id),
    commodity_raw         varchar(60) NOT NULL,
    data_type             varchar(20) NOT NULL CHECK (data_type IN ('RESOURCE','PRODUCTION')),
    measure               varchar(20) NOT NULL CHECK (measure IN ('GRADE','AMOUNT')),
    value_num             numeric,
    value_text            varchar(60),
    unit                  varchar(100),
    seq                   integer NOT NULL DEFAULT 0,
    source                varchar(120) NOT NULL DEFAULT 'SEGEMAR SIGAM ficha',
    isactive              boolean NOT NULL DEFAULT true,
    createdby             varchar(100) NOT NULL DEFAULT CURRENT_USER,
    createddate           timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (depositid, data_type, measure, commodity_raw, seq)
);
CREATE INDEX IF NOT EXISTS idx_deposit_endowment_depositid ON deposit_endowment(depositid);
CREATE INDEX IF NOT EXISTS idx_deposit_endowment_commodity ON deposit_endowment(commodity_id);

-- 2. Backups of the tables Phase 1 writes to / updates.
CREATE TABLE deposits_bak_20260910 AS SELECT * FROM deposits;
CREATE TABLE deposit_commodities_bak_20260910 AS SELECT * FROM deposit_commodities;
CREATE TABLE deposit_mineralogy_bak_20260910 AS SELECT * FROM deposit_mineralogy;
-- age_measured and deposit_endowment only receive tagged INSERTs
-- (createdby = 'claude_sigam_20260910'); no snapshot needed.

COMMIT;

